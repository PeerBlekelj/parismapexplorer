"""Write data/research/OPEN_QUESTIONS.md: places still unidentified or identified with low confidence."""
import csv, sys
from pathlib import Path
root = Path(sys.argv[1])
rows = []
for f in ("places_streets.csv", "places_others.csv"):
    rows += [r for r in csv.DictReader(open(root / "data" / f)) if not r["duplicate_of"]]
inv = {r["id"]: r for r in csv.DictReader(open(root / "data/labels_inventory.csv"))}
open_rows = sorted((r for r in rows if r["id_confidence"] == "low" or not r["status"]), key=lambda r: r["id"])
out = ["# Open questions", "",
       "Labels on the map that are not identified yet, or only tentatively. Generated by",
       "`scripts/open_questions.py`; corrections are welcome as pull requests to",
       "`data/research/streets.csv` or `data/research/others.csv`.", "",
       f"{len(open_rows)} open items.", "",
       "| id | label as printed | type | position on scan (x, y) | what we know |",
       "|---|---|---|---|---|"]
for r in open_rows:
    L = inv[r["id"]]
    out.append(f"| {r['id']} | {L['text']} | {L['type'].replace('_', ' ')} | {L['x']}, {L['y']} | {r['note'] or '—'} |")
out += ["", "## Sources still to check", "",
        "- Jules Cousin, *Plan des noms des rues, places, églises, couvents, collèges, hôtels, etc.*, "
        "Mémoires de la Société de l'histoire de Paris et de l'Île-de-France, vol. 2 (1875), pp. 58–70 — "
        "the 19th-century index of this map's names "
        "(Gallica: https://gallica.bnf.fr/ark:/12148/bpt6k6310467r/f66.item).",
        "- Félix Lazare, *Dictionnaire administratif et historique des rues de Paris* (1844).",
        "- Jacques Hillairet, *Dictionnaire historique des rues de Paris*."]
(root / "data/research/OPEN_QUESTIONS.md").write_text("\n".join(out) + "\n")
print(len(open_rows), "open items")
