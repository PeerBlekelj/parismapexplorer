"""Write data/research/OPEN_QUESTIONS.md: places still unidentified or identified with low confidence."""
import csv, sys
from pathlib import Path
root = Path(sys.argv[1])
rows = []
for f in ("places_streets.csv", "places_others.csv"):
    rows += [r for r in csv.DictReader(open(root / "data" / f)) if not r["duplicate_of"]]
inv = {r["id"]: r for r in csv.DictReader(open(root / "data/labels_inventory.csv"))}
open_rows = sorted((r for r in rows if r["id_confidence"] == "low" or not r["status"]), key=lambda r: r["id"])
out = ["# Open questions", "",
       "Labels on the map that are not identified yet, or only tentatively. Generated by",
       "`scripts/open_questions.py`; corrections are welcome as pull requests to",
       "`data/research/streets.csv` or `data/research/others.csv`.", "",
       f"{len(open_rows)} open items.", "",
       "| id | label as printed | type | position on scan (x, y) | what we know |",
       "|---|---|---|---|---|"]
for r in open_rows:
    L = inv[r["id"]]
    out.append(f"| {r['id']} | {L['text']} | {L['type'].replace('_', ' ')} | {L['x']}, {L['y']} | {r['note'] or '—'} |")
out += ["", "## Research questions", "",
        "Questions about the map's history rather than its labels. Each has its own note.", "",
        "- **Where was the Chef Saint-Denis?** The publishers' shop \"en la rue de Montorgueil, au chef Sainct-Denys\". "
        "Narrowed to today's rue Montorgueil north of the rue Mauconseil, or the rue des Petits-Carreaux; the house "
        "is not located. Next steps: read Lepape 2016 and Grivel 2008/2015 in full; the archbishop's censiers "
        "(the 1575 one lists the Bon Pasteur) chained forward to the late-18th-century parcel plans Brette published; Minutier central deeds. "
        "Note: `data/research/print_shop.md`. On the site: https://paris1550.vercel.app/#shop"]
out += ["", "## Sources", "",
        "- Checked against Jules Cousin, \"Table des noms des rues, places, églises, couvents, collèges, hôtels, etc., "
        "inscrits sur le plan de Paris publié vers 1552 par Olivier Truschet et Germain Hoyau\", *Mémoires de la Société "
        "de l'histoire de Paris et de l'Île-de-France*, t. I (1875), pp. 60–70 "
        "(Gallica: https://gallica.bnf.fr/ark:/12148/bpt6k6310467r/f68.item). Cousin lists the items above without "
        "identifying them.",
        "- Still to check: Félix Lazare, *Dictionnaire administratif et historique des rues de Paris* (1844); "
        "Jacques Hillairet, *Dictionnaire historique des rues de Paris*."]
(root / "data/research/OPEN_QUESTIONS.md").write_text("\n".join(out) + "\n")
print(len(open_rows), "open items")
